const marker = "// Code generated by TORM; DO NOT EDIT."

func fieldType(field *schema.Field) string {
	if field.Optional {
		return "*" + field.GoType
	}
	return valueType(field)
}

func valueType(field *schema.Field) string {
	if field.List {
		return "[]" + field.GoType
	}
	return field.GoType
}

func relationType(relation *schema.Relation) string {
	if relation.Many {
		return "[]*" + schema.Export(relation.Target.Name)
	}
	return "*" + schema.Export(relation.Target.Name)
}

func fieldList(fields []*schema.Field) string {
	names := make([]string, 0, len(fields))
	for _, field := range fields {
		names = append(names, strconv.Quote(field.Column))
	}
	return strings.Join(names, ", ")
}

func keyName(key schema.Key) string {
	if key.Selector != "" {
		return schema.Export(key.Selector)
	}
	names := make([]string, 0, len(key.Fields))
	for _, field := range key.Fields {
		names = append(names, schema.Export(field.Name))
	}
	return strings.Join(names, "And")
}

type templateData struct {
	*schema.Schema
	Package     string
	Environment string
	Time        bool
	UUID        bool
	JSON        bool
}

var code = template.Must(template.New("models").Funcs(template.FuncMap{
	"export": schema.Export, "quote": strconv.Quote, "fieldType": fieldType, "valueType": valueType,
	"relationType": relationType, "fieldList": fieldList, "keyName": keyName,
	"jsonTag": func(name string) string {
		return "\x60json:" + strconv.Quote(name) + "\x60"
	},
	"relationTag": func(name string) string {
		return "\x60json:" + strconv.Quote(name+",omitempty") + "\x60"
	},
	"keyField": func(model *schema.Model, field *schema.Field) bool {
		for _, key := range model.Keys {
			for _, part := range key.Fields {
				if key.Primary && part == field {
					return true
				}
			}
		}
		return false
	},
}).Parse(generatedSource))

func generationData(source *schema.Schema, packageName string) (templateData, error) {
	if !token.IsIdentifier(packageName) || packageName == "_" {
		return templateData{}, fmt.Errorf("invalid Go package name %q", packageName)
	}
	data := templateData{Schema: source, Package: packageName, Environment: source.Source.Environment}
	if data.Environment == "" {
		data.Environment = "DATABASE_URL"
	}
	names := map[string]bool{"Client": true, "Open": true, "NewClient": true, "NewClientFromDB": true}
	for _, enum := range source.Enums {
		namesForEnum := []string{schema.Export(enum.Name)}
		for _, value := range enum.Values {
			namesForEnum = append(namesForEnum, schema.Export(enum.Name)+schema.Export(value.Name))
		}
		for _, name := range namesForEnum {
			if names[name] {
				return templateData{}, fmt.Errorf("generated Go symbol %s is defined more than once", name)
			}
			names[name] = true
		}
	}
	for _, model := range source.Models {
		name := schema.Export(model.Name)
		namesForModel := []string{name, name + "Service", name + "Fields", name + "Key", name + "Create", name + "Update", name + "Include", name + "Query"}
		for _, key := range model.Keys {
			namesForModel = append(namesForModel, name+"By"+keyName(key))
		}
		for _, generated := range namesForModel {
			if names[generated] {
				return templateData{}, fmt.Errorf("%s: generated Go symbol %s is defined more than once", model.Name, generated)
			}
			names[generated] = true
		}
		for _, field := range model.Columns {
			data.Time = data.Time || field.GoType == "time.Time"
			data.UUID = data.UUID || field.UUIDVersion != 0 || field.GoType == "uuid.UUID"
			data.JSON = data.JSON || field.GoType == "json.RawMessage"
		}
	}
	return data, nil
}

func render(source *schema.Schema, packageName string) ([]byte, error) {
	data, err := generationData(source, packageName)
	if err != nil {
		return nil, err
	}
	var rendered bytes.Buffer

	if err := code.Execute(&rendered, data); err != nil {
		return nil, err
	}
	result, err := format.Source(rendered.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated Go: %w", err)
	}
	return result, nil
}

func Validate(source *schema.Schema) error {
	_, err := generationData(source, "models")
	return err
}

func Compile(source *schema.Schema, out, packageName string) error {
	result, err := render(source, packageName)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(out, 0o755); err != nil {
		return err
	}
	path := filepath.Join(out, "torm.gen.go")
	previous, err := os.ReadFile(path)
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	if err == nil && !bytes.HasPrefix(previous, []byte(marker+"\n")) && !bytes.HasPrefix(previous, []byte(marker+"\r\n")) {
		return fmt.Errorf("refusing to overwrite hand-written file %s", path)
	}
	entries, err := os.ReadDir(out)
	if err != nil {
		return err
	}
	var legacy []string

	for _, entry := range entries {
		if entry.IsDir() || entry.Type()&os.ModeSymlink != 0 || entry.Name() == filepath.Base(path) || !strings.HasSuffix(entry.Name(), ".go") {
			continue
		}
		old := filepath.Join(out, entry.Name())
		contents, err := os.ReadFile(old)
		if err != nil {
			return err
		}
		header := strings.ReplaceAll(string(contents), "\r\n", "\n")
		if strings.HasPrefix(header, "package models\n\n"+marker+"\n") {
			legacy = append(legacy, old)
		}
	}
	if !bytes.Equal(previous, result) {
		temp, err := os.CreateTemp(out, ".torm-go-*")
		if err != nil {
			return err
		}
		defer os.Remove(temp.Name())
		_, writeErr := temp.Write(result)
		closeErr := temp.Close()
		if err := errors.Join(writeErr, closeErr); err != nil {
			return err
		}
		if err := os.Rename(temp.Name(), path); err != nil {
			return err
		}
	}
	for _, old := range legacy {
		if err := os.Remove(old); err != nil {
			return err
		}
	}
	return nil
}
