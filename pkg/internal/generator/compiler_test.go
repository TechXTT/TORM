package generator

import (
	"bytes"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/TechXTT/TORM/v2/pkg/internal/schema"
)

func TestCompileIsDeterministicAndOwnsOnlyGeneratedFiles(t *testing.T) {
	source, err := schema.Load(filepath.Join("..", "schema", "testdata", "postgres"), false)
	if err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	handwritten := []byte("package local\n\nvar applicationValue = 1\n")
	const oldModel = "package models\n\n// Code generated by TORM; DO NOT EDIT.\n\ntype Gone struct{}\n"
	for path, body := range map[string][]byte{"app.go": handwritten, "gone.go": []byte(oldModel)} {
		if err := os.WriteFile(filepath.Join(dir, path), body, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	if err := Compile(source, dir, "local"); err != nil {
		t.Fatal(err)
	}
	first, err := os.ReadFile(filepath.Join(dir, "torm.gen.go"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(first), "func EntryByEntryKey(v0 int, v1 string) EntryKey") {
		t.Fatal("generated Go is missing the compound selector")
	}
	if err := Compile(source, dir, "local"); err != nil {
		t.Fatal(err)
	}
	second, err := os.ReadFile(filepath.Join(dir, "torm.gen.go"))
	if err != nil || !bytes.Equal(first, second) {
		t.Fatalf("second generation changed Go bytes: %v", err)
	}
	for _, name := range []string{"gone.go", "go.mod", "go.sum"} {
		if _, err := os.Stat(filepath.Join(dir, name)); !os.IsNotExist(err) {
			t.Fatalf("unexpected file %s: %v", name, err)
		}
	}
	actual, err := os.ReadFile(filepath.Join(dir, "app.go"))
	if err != nil || !bytes.Equal(actual, handwritten) {
		t.Fatalf("generation changed a handwritten file: %v", err)
	}
}
