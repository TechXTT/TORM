package schema

import (
	"fmt"
	"slices"
	"strings"
)

func Quoted(names []string) string {
	result := make([]string, 0, len(names))
	for _, name := range names {
		result = append(result, Quote(name))
	}
	return strings.Join(result, ", ")
}

func foreignKey(local []string, table string, remote []string, onDelete, onUpdate string) string {
	return fmt.Sprintf("FOREIGN KEY (%s) REFERENCES %s (%s) ON DELETE %s ON UPDATE %s",
		Quoted(local), Quote(table), Quoted(remote), onDelete, onUpdate)
}

func (s *Schema) DDL() string {
	var types []string
	var tables []string
	var constraints []string
	var relations []string
	var indexes []string

	for _, enum := range s.Enums {
		labels := make([]string, 0, len(enum.Values))
		for _, value := range enum.Values {
			labels = append(labels, Literal(value.Label))
		}
		types = append(types, fmt.Sprintf("CREATE TYPE %s AS ENUM (%s);", Quote(enum.Type), strings.Join(labels, ", ")))
	}
	for _, model := range s.Models {
		columnsSQL := make([]string, 0, len(model.Columns))
		for _, field := range model.Columns {
			definition := Quote(field.Column) + " " + field.SQLType
			if field.List {
				definition += "[]"
			}
			if field.Identity {
				definition += " GENERATED BY DEFAULT AS IDENTITY"
			}
			if field.Default != "" {
				definition += " DEFAULT " + field.Default
			}
			if !field.Optional {
				definition += " NOT NULL"
			}
			columnsSQL = append(columnsSQL, definition)
		}
		tables = append(tables, fmt.Sprintf("CREATE TABLE %s (\n    %s\n);", Quote(model.Table), strings.Join(columnsSQL, ",\n    ")))
		for _, key := range model.Keys {
			kind := "UNIQUE"
			if key.Primary {
				kind = "PRIMARY KEY"
			}
			constraints = append(constraints, fmt.Sprintf("ALTER TABLE %s ADD CONSTRAINT %s %s (%s);", Quote(model.Table), Quote(key.Name), kind, Quoted(columns(key.Fields))))
		}
		for _, relation := range model.Relations {
			if relation.Constraint != "" {
				relations = append(relations, fmt.Sprintf("ALTER TABLE %s ADD CONSTRAINT %s %s;", Quote(model.Table), Quote(relation.Constraint),
					foreignKey(columns(relation.Local), relation.Target.Table, columns(relation.Remote), relation.OnDelete, relation.OnUpdate)))
			}
		}
		for _, index := range model.Indexes {
			indexes = append(indexes, fmt.Sprintf("CREATE INDEX %s ON %s (%s);", Quote(index.Name), Quote(model.Table), Quoted(columns(index.Fields))))
		}
	}
	for _, join := range s.Joins {
		tables = append(tables, fmt.Sprintf("CREATE TABLE %s (\n    \"A\" %s NOT NULL,\n    \"B\" %s NOT NULL\n);", Quote(join.Table), join.AKey.SQLType, join.BKey.SQLType))
		for _, side := range []struct {
			column string
			table  string
			key    string
		}{
			{"A", join.A.Table, join.AKey.Column},
			{"B", join.B.Table, join.BKey.Column},
		} {
			relations = append(relations, fmt.Sprintf("ALTER TABLE %s ADD CONSTRAINT %s %s;", Quote(join.Table), Quote(Name(join.Table, side.column, "fkey")),
				foreignKey([]string{side.column}, side.table, []string{side.key}, "CASCADE", "CASCADE")))
		}
		indexes = append(indexes, fmt.Sprintf("CREATE UNIQUE INDEX %s ON %s (\"A\", \"B\");", Quote(Name(join.Table, "AB", "unique")), Quote(join.Table)))
		indexes = append(indexes, fmt.Sprintf("CREATE INDEX %s ON %s (\"B\");", Quote(Name(join.Table, "B", "index")), Quote(join.Table)))
	}
	var statements []string

	for _, group := range [][]string{types, tables, constraints, indexes, relations} {
		slices.Sort(group)
		statements = append(statements, group...)
	}
	return strings.Join(statements, "\n\n") + "\n"
}
