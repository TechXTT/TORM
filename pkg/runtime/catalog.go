package runtime

import (
	"context"
	"database/sql"
	"encoding/json"
	"fmt"
	"maps"
	"slices"
	"strings"

	"github.com/TechXTT/TORM/v2/pkg/internal/schema"
)

type column struct {
	Type     string
	Required bool
	Default  string
	Identity string
}

func (c column) definition(name string) string {
	definition := schema.Quote(name) + " " + c.Type
	switch c.Identity {
	case "d":
		definition += " GENERATED BY DEFAULT AS IDENTITY"
	case "a":
		definition += " GENERATED ALWAYS AS IDENTITY"
	}
	if c.Default != "" {
		definition += " DEFAULT " + c.Default
	}
	if c.Required {
		definition += " NOT NULL"
	}
	return definition
}

type constraint struct {
	Kind string
	SQL  string
}

type table struct {
	Columns     map[string]column
	Constraints map[string]constraint
	Indexes     map[string]string
}

type catalog struct {
	Tables map[string]*table
	Enums  map[string][]string
	Other  map[string]string
}

func readCatalog(ctx context.Context, tx *sql.Tx) (catalog, error) {
	result := catalog{Tables: make(map[string]*table), Enums: make(map[string][]string), Other: make(map[string]string)}
	rows, err := tx.QueryContext(ctx, `
		WITH relations AS (
			SELECT c.oid, c.relname::text AS name, c.relkind, c.relpersistence, c.relrowsecurity FROM pg_class c
			JOIN pg_namespace ns ON ns.oid = c.relnamespace
			WHERE ns.nspname = current_schema() AND c.relname <> 'schema_migrations'
		)
		SELECT 'table', name, '', '', '', '' FROM relations WHERE relkind = 'r' AND relpersistence = 'p' AND NOT relrowsecurity
		UNION ALL
		SELECT 'column', r.name, a.attname::text, format_type(a.atttypid, a.atttypmod),
			CASE
				WHEN a.attidentity <> '' THEN 'identity:' || a.attidentity::text
				WHEN pg_get_expr(d.adbin, d.adrelid) LIKE 'nextval(%' AND pg_get_serial_sequence(quote_ident(r.name), a.attname::text) IS NOT NULL THEN 'identity:d'
				ELSE COALESCE(pg_get_expr(d.adbin, d.adrelid), '')
			END,
			CASE WHEN a.attnotnull THEN 'required' ELSE '' END
		FROM relations r JOIN pg_attribute a ON a.attrelid = r.oid
		LEFT JOIN pg_attrdef d ON d.adrelid = r.oid AND d.adnum = a.attnum
		WHERE r.relkind = 'r' AND r.relpersistence = 'p' AND NOT r.relrowsecurity AND a.attnum > 0 AND NOT a.attisdropped
		UNION ALL
		SELECT 'constraint', r.name, c.conname::text, c.contype::text, pg_get_constraintdef(c.oid), ''
		FROM relations r JOIN pg_constraint c ON c.conrelid = r.oid
		WHERE r.relkind = 'r' AND r.relpersistence = 'p' AND NOT r.relrowsecurity AND c.contype <> 'n'
		UNION ALL
		SELECT 'index', r.name, i.relname::text,
			replace(pg_get_indexdef(i.oid), format('INDEX %I ON %I.%I ', i.relname, current_schema(), r.name),
				format('INDEX %I ON %I ', i.relname, r.name)), '', ''
		FROM relations r JOIN pg_index ix ON ix.indrelid = r.oid JOIN pg_class i ON i.oid = ix.indexrelid
		WHERE r.relkind = 'r' AND r.relpersistence = 'p' AND NOT r.relrowsecurity AND NOT EXISTS (
			SELECT 1 FROM pg_constraint con WHERE con.conindid = i.oid AND con.conrelid = r.oid AND con.contype IN ('p', 'u', 'x')
		)
		UNION ALL
		SELECT 'enum', t.typname::text, '', json_agg(e.enumlabel::text ORDER BY e.enumsortorder)::text, '', ''
		FROM pg_type t JOIN pg_namespace ns ON ns.oid = t.typnamespace JOIN pg_enum e ON e.enumtypid = t.oid
		WHERE ns.nspname = current_schema() GROUP BY t.typname
		UNION ALL
		SELECT 'other', 'relation', name, relkind::text || ':' || relpersistence::text, '', '' FROM relations
		WHERE relkind IN ('p', 'v', 'm', 'f') OR (relkind = 'r' AND (relpersistence <> 'p' OR relrowsecurity))
		UNION ALL
		SELECT 'other', 'trigger:' || r.name, t.tgname::text, pg_get_triggerdef(t.oid), '', ''
		FROM relations r JOIN pg_trigger t ON t.tgrelid = r.oid WHERE NOT t.tgisinternal
		UNION ALL
		SELECT 'other', 'generated:' || r.name, a.attname::text, a.attgenerated::text, '', ''
		FROM relations r JOIN pg_attribute a ON a.attrelid = r.oid WHERE a.attgenerated <> '' AND NOT a.attisdropped
	`)
	if err != nil {
		return result, err
	}
	defer rows.Close()
	for rows.Next() {
		var kind string
		var parent string
		var name string
		var definition string
		var extra string
		var flag string

		if err := rows.Scan(&kind, &parent, &name, &definition, &extra, &flag); err != nil {
			return result, err
		}
		if kind == "enum" {
			var labels []string

			if err := json.Unmarshal([]byte(definition), &labels); err != nil {
				return result, err
			}
			result.Enums[parent] = labels
			continue
		}
		if kind == "other" {
			result.Other[parent+"/"+name] = definition
			continue
		}
		entry := result.Tables[parent]
		if entry == nil {
			entry = &table{Columns: make(map[string]column), Constraints: make(map[string]constraint), Indexes: make(map[string]string)}
			result.Tables[parent] = entry
		}
		switch kind {
		case "column":
			identity, isIdentity := strings.CutPrefix(extra, "identity:")
			if isIdentity {
				extra = ""
			} else {
				identity = ""
			}
			entry.Columns[name] = column{Type: definition, Required: flag == "required", Default: extra, Identity: identity}
		case "constraint":
			entry.Constraints[name] = constraint{Kind: definition, SQL: extra}
		case "index":
			entry.Indexes[name] = definition
		}
	}
	return result, rows.Err()
}

type MigrationPlan struct {
	SQL    string
	Review []string
}

func sortedKeys[V any](values map[string]V) []string {
	return slices.Sorted(maps.Keys(values))
}

func diff(before, after catalog) (MigrationPlan, error) {
	var plan MigrationPlan
	var types []string
	var dropForeignKeys []string
	var dropOthers []string
	var changes []string
	var keys []string
	var foreignKeys []string
	var dropTypes []string
	var enumAdditions []string

	for _, name := range sortedKeys(before.Other) {
		if before.Other[name] != after.Other[name] {
			return plan, fmt.Errorf("object %s requires a reviewed manual SQL migration", name)
		}
	}
	for _, name := range sortedKeys(after.Enums) {
		target := after.Enums[name]
		previous, exists := before.Enums[name]
		if !exists {
			labels := make([]string, 0, len(target))
			for _, label := range target {
				labels = append(labels, schema.Literal(label))
			}
			types = append(types, fmt.Sprintf("CREATE TYPE %s AS ENUM (%s);", schema.Quote(name), strings.Join(labels, ", ")))
			continue
		}
		if len(previous) > len(target) || !slices.Equal(previous, target[:len(previous)]) {
			return plan, fmt.Errorf("reordering, inserting or removing values of enum %s requires a reviewed manual SQL migration", name)
		}
		for _, label := range target[len(previous):] {
			enumAdditions = append(enumAdditions, fmt.Sprintf("ALTER TYPE %s ADD VALUE %s;", schema.Quote(name), schema.Literal(label)))
		}
	}

	var refreshForeignKeys bool

	for name, previous := range before.Tables {
		target := after.Tables[name]
		if target == nil {
			refreshForeignKeys = true
			break
		}
		for field, oldColumn := range previous.Columns {
			newColumn, exists := target.Columns[field]
			if !exists || oldColumn.Type != newColumn.Type {
				refreshForeignKeys = true
			}
		}
		for key, oldConstraint := range previous.Constraints {
			if (oldConstraint.Kind == "p" || oldConstraint.Kind == "u") && oldConstraint != target.Constraints[key] {
				refreshForeignKeys = true
			}
		}
		for index, oldIndex := range previous.Indexes {
			if strings.HasPrefix(oldIndex, "CREATE UNIQUE INDEX ") && oldIndex != target.Indexes[index] {
				refreshForeignKeys = true
			}
		}
	}
	for _, name := range sortedKeys(before.Tables) {
		previous := before.Tables[name]
		target := after.Tables[name]
		quotedTable := schema.Quote(name)
		for _, key := range sortedKeys(previous.Constraints) {
			oldConstraint := previous.Constraints[key]
			if target != nil && oldConstraint == target.Constraints[key] && !(refreshForeignKeys && oldConstraint.Kind == "f") {
				continue
			}
			statement := fmt.Sprintf("ALTER TABLE %s DROP CONSTRAINT %s;", quotedTable, schema.Quote(key))
			if oldConstraint.Kind == "f" {
				dropForeignKeys = append(dropForeignKeys, statement)
			} else if target != nil {
				dropOthers = append(dropOthers, statement)
				if oldConstraint.Kind != "p" && oldConstraint.Kind != "u" {
					plan.Review = append(plan.Review, fmt.Sprintf("remove constraint %s.%s", name, key))
				}
			}
		}
		if target == nil {
			changes = append(changes, "DROP TABLE "+quotedTable+";")
			plan.Review = append(plan.Review, "drop table "+name)
			continue
		}
		for _, index := range sortedKeys(previous.Indexes) {
			if previous.Indexes[index] != target.Indexes[index] {
				dropOthers = append(dropOthers, "DROP INDEX "+schema.Quote(index)+";")
			}
		}
		for _, field := range sortedKeys(previous.Columns) {
			if _, exists := target.Columns[field]; !exists {
				changes = append(changes, fmt.Sprintf("ALTER TABLE %s DROP COLUMN %s;", quotedTable, schema.Quote(field)))
				plan.Review = append(plan.Review, fmt.Sprintf("drop column %s.%s", name, field))
			}
		}
	}
	for _, name := range sortedKeys(after.Tables) {
		target := after.Tables[name]
		previous := before.Tables[name]
		quotedTable := schema.Quote(name)
		if previous == nil {
			definitions := make([]string, 0, len(target.Columns))
			for _, field := range sortedKeys(target.Columns) {
				definitions = append(definitions, target.Columns[field].definition(field))
			}
			changes = append(changes, fmt.Sprintf("CREATE TABLE %s (\n    %s\n);", quotedTable, strings.Join(definitions, ",\n    ")))
		}
		for _, field := range sortedKeys(target.Columns) {
			if previous == nil {
				break
			}
			newColumn := target.Columns[field]
			oldColumn, exists := previous.Columns[field]
			if !exists {
				changes = append(changes, fmt.Sprintf("ALTER TABLE %s ADD COLUMN %s;", quotedTable, newColumn.definition(field)))
				if newColumn.Required && newColumn.Default == "" && newColumn.Identity == "" {
					plan.Review = append(plan.Review, fmt.Sprintf("add required column %s.%s without a database default", name, field))
				}
				continue
			}
			prefix := fmt.Sprintf("ALTER TABLE %s ALTER COLUMN %s", quotedTable, schema.Quote(field))
			if oldColumn.Identity != newColumn.Identity {
				return plan, fmt.Errorf("changing identity behavior of %s.%s requires a reviewed manual SQL migration", name, field)
			}
			typeChanged := oldColumn.Type != newColumn.Type
			if (typeChanged || oldColumn.Default != newColumn.Default) && oldColumn.Default != "" {
				changes = append(changes, prefix+" DROP DEFAULT;")
			}
			if typeChanged {
				changes = append(changes, fmt.Sprintf("%s TYPE %s USING %s::%s;", prefix, newColumn.Type, schema.Quote(field), newColumn.Type))
				plan.Review = append(plan.Review, fmt.Sprintf("change column type of %s.%s from %s to %s", name, field, oldColumn.Type, newColumn.Type))
			}
			if (typeChanged || oldColumn.Default != newColumn.Default) && newColumn.Default != "" {
				changes = append(changes, prefix+" SET DEFAULT "+newColumn.Default+";")
			}
			if oldColumn.Required != newColumn.Required {
				if newColumn.Required {
					changes = append(changes, prefix+" SET NOT NULL;")
					plan.Review = append(plan.Review, fmt.Sprintf("require non-null values in %s.%s", name, field))
				} else {
					changes = append(changes, prefix+" DROP NOT NULL;")
				}
			}
		}
		for _, key := range sortedKeys(target.Constraints) {
			newConstraint := target.Constraints[key]
			if previous != nil && newConstraint == previous.Constraints[key] && !(refreshForeignKeys && newConstraint.Kind == "f") {
				continue
			}
			statement := fmt.Sprintf("ALTER TABLE %s ADD CONSTRAINT %s %s;", quotedTable, schema.Quote(key), newConstraint.SQL)
			if newConstraint.Kind == "f" {
				foreignKeys = append(foreignKeys, statement)
			} else {
				keys = append(keys, statement)
			}
		}
		for _, index := range sortedKeys(target.Indexes) {
			if previous == nil || target.Indexes[index] != previous.Indexes[index] {
				keys = append(keys, target.Indexes[index]+";")
			}
		}
	}
	for _, name := range sortedKeys(before.Enums) {
		if _, exists := after.Enums[name]; !exists {
			dropTypes = append(dropTypes, "DROP TYPE "+schema.Quote(name)+";")
			plan.Review = append(plan.Review, "drop enum "+name)
		}
	}
	var statements []string

	for _, group := range [][]string{types, dropForeignKeys, dropOthers, changes, keys, foreignKeys, dropTypes} {
		statements = append(statements, group...)
	}
	if len(enumAdditions) > 0 && len(statements) > 0 {
		return plan, fmt.Errorf("commit enum additions in a separate migration before making other schema changes")
	}
	statements = append(statements, enumAdditions...)
	if len(statements) > 0 {
		plan.SQL = strings.Join(statements, "\n\n") + "\n"
	}
	return plan, nil
}
